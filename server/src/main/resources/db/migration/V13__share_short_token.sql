-- V13 —— 分享口令从 32 位缩短为 8 位（`Share.TOKEN_CHARS`），字段跟着从 CHAR(32) 放成 VARCHAR
--
-- ## 为什么是 8 位（账在 设计决策记录）
--
-- 去歧义字符集 31 个字符（abcdefghjkmnpqrstuvwxyz23456789，去掉 i/l/o/0/1）：
--   · 6 位 = 31^6 ≈ 8.9 亿（≈2^30）—— 分享接口是**免登录**的，而且服务端**没有任何限流**，
--     这个量级**能被脚本扫出来** → 不够
--   · 8 位 = 31^8 ≈ 8500 亿（≈2^40）—— 实用上扫不动，且仍然好念、好抄、好印在二维码上
-- 要再缩短，就得先给 /api/share/* 加限流，而不是直接减位数。这一版定 8 位。
--
-- ## 为什么要就地撤销老口令
--
-- 32 位的老口令在新规则下**已经打不开**：Share.looksLikeToken 只认 8 位，
-- 校验不过就直接 404「这个分享口令对不上」。若留着 revoked = 0，界面会说「可以用」，
-- 而客户点开得到的是一句「对不上」—— **界面说假话**（本项目最不能忍的那一类）。
-- 所以统一标成已撤销：访问时会得到 410 + 「已经被撤销」（Share.whyText），
-- 客户知道去找分享人要一条新的，而不是怀疑自己抄错了。
--
-- 实测（2026-10-08）这台机器的 scheme_share 是 0 行 —— 也就是说**没有已发出的链接会因此失效**。
-- 这条 UPDATE 留着是为了别的库、以及将来回放这段历史时，不会悄悄留下一串坏链接。
ALTER TABLE `scheme_share`
  MODIFY `token` VARCHAR(32) NOT NULL COMMENT '免登录只读的分享口令（8 位、无歧义字符集，见 Share.TOKEN_CHARS）';

UPDATE `scheme_share` SET `revoked` = 1 WHERE CHAR_LENGTH(`token`) <> 8;