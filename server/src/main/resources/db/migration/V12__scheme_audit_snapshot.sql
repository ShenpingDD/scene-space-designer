-- V12：把「判定那一刻的结论」存下来（R6-4 B4d）
--
-- 为什么必须存：B4d 之前，方案只记了 `params_rev`（"这一版是按哪版参数摆的"），
-- 但**结论没有一处落库** —— 体检是按需算的、进的是内存缓存（`AuditCache`，键 = 内容 + 参数指纹 + 目录版本）。
-- 于是「按方案存的那一版参数判，结论是什么」这个问题，一旦参数改过就**永远答不出来了**
-- （内核参数是全局的，见 `ParamsLive` 的类注释：不做"临时换一版参数算完再换回来"，
-- 因为那会让并发请求读到别人的参数、算出不属于任何一版的结论）。
--
-- 存下来之后，「双显」才有第二边可比：
--   左：`audit_json` —— **落库那一刻**服务端判的结论（含 `paramsRev` / `catalogRev`，白纸黑字）
--   右：按**现在**的参数重判一遍（`POST /api/schemes/{id}/recheck`，不写库）
--
-- 两列都**可为 NULL**，而且 NULL 有意义：
--   · 本迁移之前存的方案（id 1/2/5/16/19）就都是 NULL —— 界面必须说「**没有存下当时的结论**」，
--     **不许**拿现在的结论冒充（"缺数据不补" 是本项目的铁律）。
--   · 留痕表那一列同理：它是**留档**，只追加不回改（参数后来改了，它也不跟着变）。

ALTER TABLE scheme
  ADD COLUMN audit_json JSON NULL
  COMMENT '落库那一刻服务端判的结论（report + paramsRev + catalogRev）。NULL = 这份方案在"记结论"之前存的，不许拿现在的结论冒充';

ALTER TABLE scheme_revision
  ADD COLUMN audit_json JSON NULL
  COMMENT '这一版被创建时的结论（含当时的 paramsRev / catalogRev）。留档：不随后来的参数改动而变化';

-- 回看用的（"这一版当时的结论是什么"）：按方案取留痕时按 rev 倒序，audit_json 只是跟着取出来的列，
-- 不需要单独索引。故意不加索引 —— 索引是给查询加的，这里没有新的查询形状。